import "server-only";

import { AsyncLocalStorage } from "node:async_hooks";
import fs from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import postgres from "postgres";

type RunResult = { changes: number; lastInsertRowid: number | bigint };

type Statement = {
  get(...params: unknown[]): Promise<unknown>;
  all(...params: unknown[]): Promise<unknown[]>;
  run(...params: unknown[]): Promise<RunResult>;
};

type Db = {
  prepare(sql: string): Statement;
  exec(sql: string): Promise<void>;
};

type QueryClient = {
  unsafe(
    query: string,
    parameters?: Array<string | number | boolean | null>,
  ): Promise<Array<Record<string, unknown>> & { count: number }>;
  reserve(): Promise<QueryClient & { release(): void }>;
};

type SessionState = {
  holding: boolean;
  reserved: (QueryClient & { release(): void }) | null;
};

const sessions = new AsyncLocalStorage<SessionState>();

function session(): SessionState {
  const current = sessions.getStore();
  if (current) return current;
  const created: SessionState = { holding: false, reserved: null };
  sessions.enterWith(created);
  return created;
}

